export interface ApiErrorBody {
  error: {
    code: ErrorCode
    message: string
    /** Zod field errors keyed by dotted path, e.g. { "email": ["Invalid email"] } */
    fieldErrors?: Record<string, string[]>
    /** Correlates with server logs; shown to users as "Reference: …" */
    requestId?: string
  }
}
